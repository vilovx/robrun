  var LANGS = ["lv", "en", "ru"];
  var LOCALE = { lv: "lv-LV", en: "en-GB", ru: "ru-RU" };
  var STORAGE = "hl_lang";

  function valid(c) { return LANGS.indexOf(c) !== -1; }
  function pick() {
    try {
      var q = new URLSearchParams(location.search).get("lang");
      if (valid(q)) return q;
    } catch (e) {}
    try {
      var s = localStorage.getItem(STORAGE);
      if (valid(s)) return s;
    } catch (e) {}
    return "lv";
  }
  var LANG = pick();

  function t(key, vars) {
    var dict = I18N[LANG] || I18N.lv;
    var s = (dict[key] != null) ? dict[key] : (I18N.lv[key] != null ? I18N.lv[key] : key);
    if (vars) Object.keys(vars).forEach(function (k) {
      s = String(s).split("{" + k + "}").join(String(vars[k]));
    });
    return s;
  }
  function rpcErr(msg, fallbackKey) {
    if (msg && RPC[msg]) return t(RPC[msg]);
    return msg || t(fallbackKey || "err_generic");
  }
  function apply() {
    document.documentElement.lang = LANG;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    document.querySelectorAll("[data-i18n-content]").forEach(function (el) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    });
    var title = document.querySelector("title[data-i18n]");
    if (title) document.title = t(title.getAttribute("data-i18n"));
    document.querySelectorAll(".hl-lang button").forEach(function (b) {
      var on = b.getAttribute("data-lang") === LANG;
      b.classList.toggle("is-on", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });
    try { document.dispatchEvent(new CustomEvent("hl:lang", { detail: LANG })); } catch (e) {}
  }
  function setLang(code) {
    if (!valid(code) || code === LANG) return;
    LANG = code;
    try { localStorage.setItem(STORAGE, code); } catch (e) {}
    apply();
  }
  function bind() {
    apply();
    document.querySelectorAll(".hl-lang button").forEach(function (b) {
      if (b.getAttribute("data-hl-bound")) return;
      b.setAttribute("data-hl-bound", "1");
      b.addEventListener("click", function () { setLang(b.getAttribute("data-lang")); });
    });
  }


  function authorityUnit(n, lang) {
    n = Math.abs(Math.trunc(Number(n)));
    if (!isFinite(n)) n = 0;
    lang = lang || LANG;
    if (lang === "en") return n === 1 ? "year" : "years";
    if (lang === "ru") {
      var mod10 = n % 10, mod100 = n % 100;
      if (mod10 === 1 && mod100 !== 11) return "год";
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "года";
      return "лет";
    }
    if (n % 10 === 1 && n % 100 !== 11) return "gads";
    return "gadi";
  }
  function formatAuthority(n, lang) {
    if (n == null || n === "") return "";
    var v = Number(n);
    if (!isFinite(v)) return "";
    v = Math.trunc(v);
    return v + " " + authorityUnit(v, lang);
  }

